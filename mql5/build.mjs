// Bundles each EA/script with its QT includes into ONE .mq5 file, and (on Windows with MT5 installed)
// compiles them, so a user downloads a ready .ex5: no Include folder, no MetaEditor, no F7.
//   node mql5/build.mjs            writes apps/web/public/ea/*.mq5
//   node mql5/build.mjs --compile  also compiles them to *.ex5 with the local MetaEditor (Windows)
//   node mql5/build.mjs --check    fails if the .mq5 bundles, or the .ex5 built from them, are out of date
// .mq5 output is UTF-8 with BOM: MetaEditor needs the BOM to read the Vietnamese messages correctly.
// ex5.json records the SHA-256 of the bundle each .ex5 was compiled from, so --check (run in npm test,
// also on Linux CI) catches a source change that was not recompiled.
// MetaEditor is found in "C:\Program Files\*\MetaEditor64.exe" (or QT_METAEDITOR), the standard
// library in %APPDATA%\MetaQuotes\Terminal\*\MQL5 (or QT_MQL5_DIR).
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, copyFileSync, mkdtempSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = [
  ["Experts/QT_MasterSender.mq5", "QT_MasterSender.mq5"],
  ["Experts/QT_Receiver.mq5", "QT_Receiver.mq5"],
  ["Scripts/QT_SelfTest.mq5", "QT_SelfTest.mq5"],
];
// Served by the web app at /ea/<file> (dist/ folders are gitignored, so the bundles live in public/).
const OUT = join(here, "..", "apps", "web", "public", "ea");
const MANIFEST = join(OUT, "ex5.json");
const BOM = "\uFEFF";
const sha = (s) => createHash("sha256").update(s).digest("hex");

/** Inline `#include <QT\X.mqh>` and `#include "X.mqh"` (from Include/QT), each file once. */
export function bundle(path, seen = new Set()) {
  const text = readFileSync(path, "utf8").replace(/^\uFEFF/, "");
  return text.split("\n").map((line) => {
    const m = /^#include\s+(?:<QT\\([\w.]+)>|"([\w.]+)")\s*$/.exec(line.trim());
    if (!m) return line;
    const name = m[1] ?? m[2];
    if (seen.has(name)) return `// (already included: ${name})`;
    seen.add(name);
    return `//==== begin ${name} ====\n${bundle(join(here, "Include", "QT", name), seen)}\n//==== end ${name} ====`;
  }).join("\n");
}

export function build() {
  return SOURCES.map(([src, out]) => {
    const body = bundle(join(here, src));
    const header = `// GENERATED by mql5/build.mjs from mql5/${src} and mql5/Include/QT. Edit those, then run: node mql5/build.mjs --compile\n`;
    return [out, BOM + header + body];
  });
}

function findMetaEditor() {
  if (process.env.QT_METAEDITOR) return process.env.QT_METAEDITOR;
  for (const root of ["C:\\Program Files", "C:\\Program Files (x86)"]) {
    if (!existsSync(root)) continue;
    for (const d of readdirSync(root)) {
      const p = join(root, d, "MetaEditor64.exe");
      if (existsSync(p)) return p;
    }
  }
  return null;
}

function findMql5Dir() {
  if (process.env.QT_MQL5_DIR) return process.env.QT_MQL5_DIR;
  const base = join(process.env.APPDATA ?? "", "MetaQuotes", "Terminal");
  if (!existsSync(base)) return null;
  for (const d of readdirSync(base)) {
    const p = join(base, d, "MQL5");
    if (existsSync(join(p, "Include", "Trade", "Trade.mqh"))) return p;
  }
  return null;
}

/** Compiles each bundle; returns the manifest entries. Throws with the compiler log on any error. */
function compile(outputs) {
  const me = findMetaEditor();
  const inc = findMql5Dir();
  if (!me || !inc) throw new Error("--compile needs MT5 on Windows (set QT_METAEDITOR and QT_MQL5_DIR if not found)");
  const work = mkdtempSync(join(tmpdir(), "qt-ea-"));
  const manifest = {};
  for (const [name, content] of outputs) {
    const src = join(work, name);
    const log = src.replace(/\.mq5$/, ".log");
    writeFileSync(src, content, "utf8");
    try { execFileSync(me, [`/compile:${src}`, `/inc:${inc}`, `/log:${log}`], { stdio: "ignore" }); } catch { /* MetaEditor exits non-zero on success */ }
    const text = existsSync(log) ? readFileSync(log).toString("utf16le") : "";
    const result = /Result: (\d+) errors?, (\d+) warnings?/.exec(text);
    const ex5 = src.replace(/\.mq5$/, ".ex5");
    if (!result || result[1] !== "0" || !existsSync(ex5)) throw new Error(`compile failed: ${name}\n${text}`);
    const out = name.replace(/\.mq5$/, ".ex5");
    copyFileSync(ex5, join(OUT, out));
    manifest[out] = { source: name, source_sha256: sha(content), warnings: Number(result[2]) };
    console.log(`compiled ${out} (${result[2]} warnings)`);
  }
  return manifest;
}

const check = process.argv.includes("--check");
const outputs = build();
if (check) {
  let stale = 0;
  for (const [name, content] of outputs) {
    const file = join(OUT, name);
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) { console.error(`out of date: ${file}`); stale++; }
  }
  const manifest = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, "utf8")) : {};
  for (const [ex5, m] of Object.entries(manifest)) {
    const cur = outputs.find(([n]) => n === m.source);
    if (!cur || sha(cur[1]) !== m.source_sha256 || !existsSync(join(OUT, ex5))) { console.error(`out of date: ${ex5} (recompile)`); stale++; }
  }
  if (stale) { console.error("Run on Windows with MT5: node mql5/build.mjs --compile"); process.exit(1); }
  console.log("mql5 bundles and ex5 up to date");
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [name, content] of outputs) writeFileSync(join(OUT, name), content, "utf8");
  if (process.argv.includes("--compile")) writeFileSync(MANIFEST, JSON.stringify(compile(outputs), null, 2) + "\n");
  console.log("mql5 bundles written");
}
