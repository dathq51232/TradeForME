// Bundles each EA/script with its QT includes into ONE .mq5 file, so a user copies a single file into
// MQL5/Experts (or Scripts) and compiles it: no Include folder to set up.
//   node mql5/build.mjs          writes apps/web/public/ea/*.mq5
//   node mql5/build.mjs --check  fails if those files are out of date (run in npm test)
// Output is UTF-8 with BOM: MetaEditor needs the BOM to read the Vietnamese messages correctly.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = [
  ["Experts/QT_MasterSender.mq5", "QT_MasterSender.mq5"],
  ["Experts/QT_Receiver.mq5", "QT_Receiver.mq5"],
  ["Scripts/QT_SelfTest.mq5", "QT_SelfTest.mq5"],
];
// Served by the web app at /ea/<file> (dist/ folders are gitignored, so the bundles live in public/).
const OUT_DIRS = [join(here, "..", "apps", "web", "public", "ea")];
const BOM = "﻿";

/** Inline `#include <QT\X.mqh>` and `#include "X.mqh"` (from Include/QT), each file once. */
export function bundle(path, seen = new Set()) {
  const text = readFileSync(path, "utf8").replace(/^﻿/, "");
  return text.split("\n").map((line) => {
    const m = /^#include\s+(?:<QT\\([\w.]+)>|"([\w.]+)")\s*$/.exec(line.trim());
    if (!m) return line;
    const name = m[1] ?? m[2];
    if (seen.has(name)) return `// (already included: ${name})`;
    seen.add(name);
    return `//==== begin ${name} ====\n${bundle(join(here, "Include", "QT", name), seen)}\n//==== end ${name} ====`;
  }).join("\n");
}

export function build() {
  return SOURCES.map(([src, out]) => {
    const body = bundle(join(here, src));
    const header = `// GENERATED by mql5/build.mjs from mql5/${src} and mql5/Include/QT. Edit those, then run: node mql5/build.mjs\n`;
    return [out, BOM + header + body];
  });
}

const check = process.argv.includes("--check");
let stale = 0;
for (const [name, content] of build()) {
  for (const dir of OUT_DIRS) {
    const file = join(dir, name);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== content) { console.error(`out of date: ${file}`); stale++; }
    } else {
      mkdirSync(dir, { recursive: true });
      writeFileSync(file, content, "utf8");
    }
  }
}
if (check && stale) { console.error("Run: node mql5/build.mjs"); process.exit(1); }
console.log(check ? "mql5 bundles up to date" : "mql5 bundles written");
